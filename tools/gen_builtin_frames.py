"""Freeze N0067's built-in frame definitions and inertial constants."""
from pathlib import Path
import csv
import spiceypy as spice

root = Path(__file__).resolve().parents[1]
rows = []
for identifier in spice.bltfrm(-1):
    center, frame_class, class_id = spice.frinfo(identifier)
    # FrameDef.rotation maps the local frame into its parent (J2000).
    rotation = spice.pxform(spice.frmnam(identifier), 'J2000', 0.).tolist() if frame_class == 1 else None
    rows.append((int(identifier),spice.frmnam(identifier),int(center),int(frame_class),int(class_id),rotation))
source = '''// Generated by tools/gen_builtin_frames.py from CSPICE N0067 built-in
// frame data (FRINFO/FRMNAM/IRFROT), not time-dependent sampled geometry.
pub(crate) struct BuiltinFrame {
    pub id: i32, pub name: &'static str, pub center: i32,
    pub class: i32, pub class_id: i32,
    pub rotation: Option<[[f64;3];3]>,
}
pub(crate) const FRAMES: &[BuiltinFrame] = &[\n'''
for identifier,name,center,frame_class,class_id,rotation in rows:
    matrix = 'None' if rotation is None else 'Some('+repr(rotation)+')'
    source += f'    BuiltinFrame {{ id:{identifier}, name:"{name}", center:{center}, class:{frame_class}, class_id:{class_id}, rotation:{matrix} }},\n'
source += '];\n'
(root/'src/frames/builtin_frames.rs').write_text(source)
with (root/'tests/golden/builtin_frames.csv').open('w',newline='') as file:
    writer=csv.writer(file);writer.writerow(['id','name','center','class','class_id'])
    writer.writerows(row[:5] for row in rows)
print(f'Generated {len(rows)} official built-in frame definitions')
