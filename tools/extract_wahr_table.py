"""Extract the pinned N0067 ZZWAHR integer coefficients, without recalculation."""
from pathlib import Path
import re,hashlib
root=Path(__file__).resolve().parents[1]
path=root/'target/reference/n0067/cspice/src/cspice/zzwahr.c'
text=path.read_text();literal=re.search(r'matrix\[954\].*?=\s*\{(.*?)\};',text,re.S).group(1)
values=list(map(int,re.findall(r'-?\d+',literal)));assert len(values)==954
output='//! N0067 ZZWAHR coefficients; generated by tools/extract_wahr_table.py.\n'
output+=f'//! Source SHA256: {hashlib.sha256(path.read_bytes()).hexdigest()}\n'
output+='pub(crate) const WAHR: [[i32;9];106] = [\n'
output+=''.join('    ['+','.join(map(str,values[i:i+9]))+'],\n' for i in range(0,954,9))+'];\n'
(root/'src/frames/wahr_table.rs').write_text(output)
