"""Generate frame-rotation golden vectors with CSPICE.

Writes a deterministic frame kernel (`tests/golden/frames.tf`) and then
evaluates `pxform` for every ordered pair of frames in it, storing the
nine matrix elements in a committed CSV. `tests/frame_golden.rs` loads
the same kernel and compares.

The kernel covers all three `TKFRAME_SPEC` forms, every angle unit, and
multi-frame relative chains. Values are computed by CSPICE, not by this
script, so the CSV is an independent oracle.

Offline tooling only; needs `spiceypy`.

Usage:
    python tools/gen_frame_golden.py
"""

from __future__ import annotations

