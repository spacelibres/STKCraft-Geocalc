import spiceypy as spice


def rot1(angle: float) -> list[list[float]]:
    sin, cos = math.sin(angle), math.cos(angle)
    return [[1.0, 0.0, 0.0], [0.0, cos, sin], [0.0, -sin, cos]]


def rot2(angle: float) -> list[list[float]]:
    sin, cos = math.sin(angle), math.cos(angle)
    return [[cos, 0.0, -sin], [0.0, 1.0, 0.0], [sin, 0.0, cos]]


def rot3(angle: float) -> list[list[float]]:
    sin, cos = math.sin(angle), math.cos(angle)
    return [[cos, sin, 0.0], [-sin, cos, 0.0], [0.0, 0.0, 1.0]]


def matmul(a: list[list[float]], b: list[list[float]]) -> list[list[float]]:
    return [
        [sum(a[row][k] * b[k][column] for k in range(3)) for column in range(3)]
        for row in range(3)
    ]


def build_kernel() -> str:
    # A genuine rotation, listed column by column as NAIF requires.
    matrix = matmul(
        matmul(rot3(math.radians(15.0)), rot1(math.radians(-25.0))),
        rot2(math.radians(40.0)),
    )
    columns = [matrix[row][column] for column in range(3) for row in range(3)]
    matrix_text = ",\n                                ".join(
        ", ".join(f"{value!r}" for value in columns[index : index + 3])
        for index in range(0, 9, 3)
    )

