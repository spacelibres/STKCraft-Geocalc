def generate_angular_size():
    import ctypes as ct, math
    from spiceypy.utils.libspicehelper import libspice
    spice.furnsh(str(OUT.parents[1]/'target/kernels/de440s.bsp'))
    spice.furnsh(str(OUT.parents[1]/'target/kernels/pck00011.tpc'))
    lines=['# N0067 SPKPOS,EDLIMB,ZZASRYEL and spherical half-angle source primitives','target,observer,correction,et,method,value']
    extents=['# N0067 EDLIMB/ZZASRYEL MIN/MAX full angular extents','target,observer,correction,et,min_size,max_size']
    for target,observer,frame in [(301,399,'IAU_MOON'),(399,301,'IAU_EARTH'),(299,399,'IAU_VENUS')]:
        radii=spice.bodvrd(str(target),'RADII',3)[1]
        for correction in ['NONE','LT','LT+S','CN','CN+S','XLT','XLT+S','XCN','XCN+S']:
            for et in [-2e9,0.,2e9]:
                center,lt=spice.spkpos(str(target),et,'J2000',correction,str(observer));distance=spice.vnorm(center)
                epoch=et if correction=='NONE' else et+(lt if correction.startswith('X') else -lt)
                view=-spice.mxv(spice.pxform('J2000',frame,epoch),center)
                ellipse=spice.edlimb(*radii,view)
                el=(ct.c_double*9)(*ellipse.center,*ellipse.semi_major,*ellipse.semi_minor)
                v=(ct.c_double*3)(*view);d=(ct.c_double*3)(*(-view));angle=ct.c_double();point=(ct.c_double*3)()
                libspice.zzasryel_(b'MIN',el,v,d,ct.byref(angle),point,ct.c_int(3))
                max_angle=ct.c_double();max_point=(ct.c_double*3)()
                libspice.zzasryel_(b'MAX',el,v,d,ct.byref(max_angle),max_point,ct.c_int(3))
                extents.append(','.join(map(str,[target,observer,correction,et,2*abs(angle.value),2*abs(max_angle.value)])))
                for method,value in [('LIMB_EXTENTS',2*abs(angle.value)),('MAX_RADIUS',2*math.asin(max(radii)/distance)),('MIN_RADIUS',2*math.asin(min(radii)/distance))]:
                    lines.append(','.join(map(str,[target,observer,correction,et,method,value])))
    (OUT/'gf_angular_size.csv').write_text('\n'.join(lines)+'\n')
    (OUT/'gf_angular_extents.csv').write_text('\n'.join(extents)+'\n')
    spice.kclear();print(f'{len(lines)-2} exact angular size primitive cases generated')

