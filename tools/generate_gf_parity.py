def generate_position_trace():
    import ctypes as ct
    from spiceypy.utils.callbacks import SpiceUDFUNS,SpiceUDFUNB
    from spiceypy.utils.libspicehelper import libspice
    spice.furnsh(str(OUT.parents[1]/'target/kernels/de440s.bsp'))
    spice.furnsh(str(OUT.parents[1]/'target/kernels/pck00011.tpc'))
    radii=spice.bodvrd('EARTH','RADII',3)[1];re=float(radii[0]);flat=float((radii[0]-radii[2])/radii[0]);lines=[]
    def value(t):
        p,_=spice.spkpos('MOON',t,'IAU_EARTH','LT','EARTH');alt=spice.recpgr('EARTH',p,re,flat)[2]
        lines.append(','.join(map(str,['V',repr(t),repr(float(alt))])))
        return alt
    def decreasing(_,t):
        state,_=spice.spkezr('MOON',t,'IAU_EARTH','LT','EARTH')
        signs=(ct.c_int*3)();sense=ct.c_int(1);radius=ct.c_double(re);f=ct.c_double(flat);sv=(ct.c_double*6)(*state)
        libspice.zzgfcprx_(sv,b'PLANETOGRAPHIC',ct.byref(radius),ct.byref(f),ct.byref(sense),signs,ct.c_int(14))
        dec=signs[2]<0;lines.append(','.join(map(str,['D',repr(t),int(dec),*[repr(float(x)) for x in state]])))
        return dec
    result=SPICEDOUBLE_CELL(1000);spice.gfstol(1e-6)
    spice.gfuds(SpiceUDFUNS(value),SpiceUDFUNB(decreasing),'=',385000.,0.,3600.,1000,cell([(0.,2592000.)]),result)
    (OUT/'gf_position_trace.csv').write_text('\n'.join(lines)+'\n');spice.kclear()
    print(f'{len(lines)} independent GFUDS/ZZGFCPRX callback trace points generated')

