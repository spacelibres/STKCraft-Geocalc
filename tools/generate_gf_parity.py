def generate_coordinates():
    vectors=[(0.,0.,0.),(1.,2.,3.),(-1.,-2.,-3.),(1e200,2e200,3e200),(1e-200,2e-200,3e-200),(0.,0.,-1.),(-1.,-0.,0.)]
    lines=['# N0067 rectangular coordinate conversions; exact binary64','system,east,x,y,z,a,c,u,v,w']
    for system,fn in [('LATITUDINAL',spice.reclat),('RA/DEC',spice.recrad),('SPHERICAL',spice.recsph),('CYLINDRICAL',spice.reccyl)]:
        for p in vectors:
            value=fn(p)
            lines.append(','.join(map(str,[system,1,*p,1.,1.,*value])))
    for ccw in [False,True]:
        for up in [False,True]:
            for p in vectors:
                r,az,el=spice.recazl(p,ccw,up)
                lines.append(','.join(map(str,[f'AZEL_{int(ccw)}_{int(up)}',1,*p,1.,1.,az,el,r])))
    for system in ['GEODETIC','PLANETOGRAPHIC']:
        for a,c in [(6378.1366,6356.7519),(1737.4,1737.4),(5.,7.)]:
            for p in [(1e8,2e8,3e8),(-1e5,1e5,-1e5),(0.,0.,1e8),(0.,0.,0.),(1.,2.,3.),(a,0.,0.),(0.,0.,c),(.2*a,.3*a,.1*c)]:
                for east in ([1] if system=='GEODETIC' else [0,1]):
                    if system=='GEODETIC':value=spice.recgeo(p,a,(a-c)/a)
                    else:
                        spice.pcpool('BODY999_PGR_POSITIVE_LON',['EAST' if east else 'WEST'])
                        value=spice.recpgr('999',p,a,(a-c)/a)
                    lines.append(','.join(map(str,[system,east,*p,a,c,*value])))
    (OUT/'gf_coordinates.csv').write_text('\n'.join(lines)+'\n')
