"""Reproduce strict GF window fixtures with CSPICE via SpiceyPy (N0067).

Run from repository root. Source contracts: wnvald, wncomd, wnexpd,
wncond, wnfild, wnfltd; no numeric tolerances or rounded outputs.
The SPK fixture provides a constant Venus vector for PCK direction tests.
"""
from pathlib import Path
import random
import numpy as np
import spiceypy as spice
from spiceypy.utils.support_types import SPICEDOUBLE_CELL

OUT = Path(__file__).resolve().parents[1] / "tests" / "golden"

def serialize(window):
    values = list(window)
    return ";".join(f"{values[i]!r}:{values[i+1]!r}" for i in range(0, len(values), 2))

def cell(intervals):
    result = SPICEDOUBLE_CELL(1000)
    for left, right in intervals:
        spice.wninsd(left, right, result)
    return result

def main():
    rng = random.Random(687)
    cases = [[], [(0.,0.)], [(1.,3.),(7.,11.),(23.,27.),(29.,29.)], [(0.,1.),(1.0000001,2.)]]
    for _ in range(36):
        cases.append([(a:=rng.randint(-30,30)/4, a+rng.randint(0,12)/4) for _ in range(rng.randint(1,12))])
    lines = [f"# {spice.tkvrsn('TOOLKIT')}; exact binary64 endpoints; generated by tools/generate_gf_parity.py", "operation,left,right,input,expected"]
    for intervals in cases:
        for operation,left,right in [("normalize",0.,0.),("complement",-3.,5.),("expand",1.25,2.5),("expand",-1.,-.5),("contract",.5,1.),("contract",-2.,2.),("fill",.5,0.),("filter",1.,0.)]:
            w = cell(intervals)
            if operation == 'complement': result = spice.wncomd(left,right,w)
            elif operation == 'expand': spice.wnexpd(left,right,w); result = w
            elif operation == 'contract': spice.wncond(left,right,w); result = w
            elif operation == 'fill': spice.wnfild(left,w); result = w
            elif operation == 'filter': spice.wnfltd(left,w); result = w
            else: result = w
            raw = ';'.join(f'{a!r}:{b!r}' for a,b in intervals)
            lines.append(f'{operation},{left!r},{right!r},{raw},{serialize(result)}')
    (OUT/'gf_windows.csv').write_text('\n'.join(lines)+'\n')
    p = OUT/'gf_fixed.bsp'
    if p.exists(): p.unlink()
    h = spice.spkopn(str(p),'GF parity fixture',0)
    try:
        spice.spkw02(h,299,0,'J2000',-10.,10.,'CONSTANT VENUS',20.,1,0,np.array([1e8,1e8,1e8]),-10.)
        spice.spkw02(h,10001,0,'J2000',-10.,10.,'POINT FRONT',20.,1,0,np.array([1e6,0.,0.]),-10.)
        spice.spkw02(h,10002,0,'J2000',-10.,10.,'ELLIPSOID BACK',20.,1,0,np.array([2e6,0.,0.]),-10.)
    finally: spice.spkcls(h)
    print(f'{len(lines)-2} exact CSPICE window cases and constant Venus SPK generated')

def generate_scalars():
    from spiceypy.utils.callbacks import SpiceUDFUNS, SpiceUDFUNB
    functions = [
        ('small_linear',lambda t:1e-9*t,lambda t:False),
        ('linear',lambda t:t,lambda t:False),
        ('quadratic',lambda t:t*t,lambda t:t<0),
        ('negative_quadratic',lambda t:-t*t,lambda t:t>0),
        ('cubic',lambda t:t*(t-2)*(t+2),lambda t:3*t*t-4<0),
        ('constant',lambda t:2.,lambda t:False),
    ]
    lines = [f"# {spice.tkvrsn('TOOLKIT')}; GFUDS with exact supplied derivative sign",'function,relation,reference,adjustment,start,end,step,tolerance,expected']
    for name,fn,dec in functions:
        for relation,reference,adjustment in [('=',0.,0.),('<',0.,0.),('>',0.,0.),('LOCMIN',0.,0.),('LOCMAX',0.,0.),('ABSMIN',0.,0.),('ABSMAX',0.,0.),('ABSMIN',0.,1.),('ABSMAX',0.,1.)]:
            confinement=cell([(-4.,4.)]); result=SPICEDOUBLE_CELL(1000)
            spice.gfstol(1e-6)
            spice.gfuds(SpiceUDFUNS(fn),SpiceUDFUNB(lambda u,t:dec(t)),relation,reference,adjustment,1.,100,confinement,result)
            lines.append(f'{name},{relation},{reference},{adjustment},-4.0,4.0,1.0,1e-6,{serialize(result)}')
    (OUT/'gf_scalars.csv').write_text('\n'.join(lines)+'\n')
    print(f'{len(lines)-2} exact GFUDS scalar cases generated')

